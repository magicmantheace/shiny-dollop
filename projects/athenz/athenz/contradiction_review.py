def _existing_home(home: Path | None) -> Path:
    location = _home_location(home)
    db = location / 'identity.sqlite3'
    if not location.is_dir() or db.is_symlink() or not db.is_file():
        raise ContradictionReviewError('An existing private AthenZ profile database is required')
    return location


def scan_profile(home: Path | None) -> dict:
    return ContradictionStore(_existing_home(home)).scan()


def list_profile(home: Path | None, *, state: str = 'actionable',
                 limit: int = 80) -> dict:
    """Metadata-only candidate list; no record text or fragments are emitted."""
    store = ContradictionStore(_existing_home(home))
    items = []
    for candidate in store.candidates(state=state, limit=limit):
        items.append({
            'id': candidate['id'], 'state': candidate['state'],
            'route': candidate['route'], 'score': candidate['score'],
            'pair': f"{candidate['a_table']}#{candidate['a_id']} x "
                    f"{candidate['b_table']}#{candidate['b_id']}",
            'jaccard': candidate['signals'].get('jaccard'),
            'slot': candidate['signals'].get('slot'),
            'records_still_approved': candidate['records_still_approved'],
        })
    return {'schema': 1, 'filter': state, 'shown': len(items), 'candidates': items,
            'private_data_in_output': False}


def show_profile(home: Path | None, candidate_id: int, *, confirmed: bool = False) -> dict:
    """Print full PRIVATE records and signals only after explicit consent."""
    if confirmed is not True:
        raise ContradictionReviewError(
            'Explicit --confirm required before displaying private record details')
    return ContradictionStore(_existing_home(home)).detail(candidate_id)


def adjudicate_profile(home: Path | None, candidate_id: int, *, action: str,
                       resolution: str | None = None, note: str = '',
                       confirmed: bool = False) -> dict:
    return ContradictionStore(_existing_home(home)).adjudicate(
        candidate_id, action=action, resolution=resolution, note=note,
        confirmed=confirmed)
