"""Deterministic contradiction candidates over approved memory, with
explicit owner adjudication (v0.3: semantic contradiction matching and
explicit owner adjudication UI).

Detection is lexical, never inferential. It pairs APPROVED identity,
decision and episode records that share a topic signal (shared episode
tags, a shared structured slot, or high token overlap) AND show one of
three documented opposition signals:

- ``negation-asymmetry``: two statements whose content tokens are
  near-identical once negation markers are removed, where exactly one
  side is negated ("I exercise every morning" / "I do not exercise
  every morning").
- ``opposite-preference``: documented first-person marker patterns with
  the same object and opposite polarity ("I prefer X" / "I avoid X",
  "I always ..." / "I never ...").
- ``conflicting-slot``: the same conservatively extracted slot with
  different values — an identical decision-scenario token signature
  with a different choice, a reversed "prefer A over B" pair, or the
  same "my favourite <slot> is ..." slot with different values.

A candidate is a PROPOSAL ONLY. Detection never modifies the records it
scans, and an un-adjudicated candidate changes nothing. The owner
adjudicates each candidate (confirm with keep A / keep B / keep both,
dismiss, or defer); only a confirmed keep-A/keep-B adjudication changes
a record, and it does so through the existing supersession machinery —
the loser leaves the approved set via the same status transition and
append-only ``superseded`` event the episode conflict review uses —
with the candidate id recorded as provenance in the adjudication log.

This is not understanding. False positives are expected (that is why
adjudication exists) and paraphrased or synonym-swapped contradictions
are guaranteed to be missed. See docs/CONTRADICTION_REVIEW.md.
"""
from __future__ import annotations

from contextlib import contextmanager
import hashlib
import json
from pathlib import Path
import re
import unicodedata

from .experience import ExperienceStore
from .profile_health import _home_location
from .store import utc_now

ROUTES = ('conflicting-slot', 'opposite-preference', 'negation-asymmetry')
CANDIDATE_STATES = frozenset({'pending', 'confirmed', 'dismissed', 'deferred'})
TABLES = ('identity', 'decisions', 'episodes')

MAX_SCAN_PER_TABLE = 1500     # refuse a partial scan beyond this, like the consistency audit
MAX_BUCKET_RECORDS = 200      # a token shared by more records is not a useful pairing gate
MAX_PAIRS_PER_SIGNAL = 40     # deterministic cap on pairs generated by one signal key
MAX_NEW_PER_SCAN = 500        # deterministic cap on candidates created by one scan
NEGATION_JACCARD_MIN = 0.75
FRAGMENT_MAX = 200
MAX_NOTE = 1000

_ROUTE_BASE = {'conflicting-slot': 0.9, 'opposite-preference': 0.85,
               'negation-asymmetry': 0.8}

_TOKEN = re.compile(r"[a-z0-9]+(?:'[a-z0-9]+)?")
_SENTENCE_SPLIT = re.compile(r"[.!?;\n]+")
_STOP = frozenset(
    "the a an and or of to in on at for with from this that it is are was were "
    "be been i my me we our you your he she they them their his her its as by "
    "do does did have has had will would can could should may might than then "
    "so such if but not no never".split())
_NEGATIONS = frozenset({
    'not', 'no', 'never', "don't", "doesn't", "didn't", "isn't", "aren't",
    "won't", "can't", "couldn't", "shouldn't", "wouldn't", "haven't",
    "hasn't", "hadn't", 'cannot',
})

_POS_VERB = r"(prefer|like|love|enjoy|want|choose)"
_MARKER_POS = re.compile(rf"^i {_POS_VERB} (.+)$")
_MARKER_NEG_VERB = re.compile(r"^i (avoid|dislike|hate|detest|reject) (.+)$")
_MARKER_NEGATED = re.compile(rf"^i (?:do not|don't|no longer) {_POS_VERB} (.+)$")
_FREQ_POS = re.compile(r"^i always (.+)$")
_FREQ_NEG = re.compile(r"^i never (.+)$")
_REVERSAL = re.compile(r"^(?:i )?(?:prefer|choose) (.+?) over (.+)$")
_FAVORITE = re.compile(r"^(?:my )?(?:favourite|favorite) ([a-z0-9][a-z0-9 -]*?) is (.+)$")


class ContradictionReviewError(ValueError):
    """A contradiction scan or adjudication fell outside its boundaries."""


# ---------------------------------------------------------------------------
# Text analysis (pure, deterministic)
# ---------------------------------------------------------------------------

def _normalize(text: str) -> str:
    folded = unicodedata.normalize('NFKC', text).casefold()
    folded = folded.replace('\u2019', "'")
    return ' '.join(_TOKEN.findall(folded))


def _tokens(text: str) -> list[str]:
    return _TOKEN.findall(_normalize(text))


def _content(tokens) -> frozenset:
    return frozenset(t for t in tokens if t not in _STOP)


def _sentences(text: str) -> list[str]:
    return [part.strip() for part in _SENTENCE_SPLIT.split(text) if part.strip()]


def _fragment(sentence: str) -> str:
    return sentence[:FRAGMENT_MAX]


def _jaccard(a: frozenset, b: frozenset) -> float:
    if not a or not b:
        return 0.0
    return len(a & b) / len(a | b)


def _score(route: str, jaccard: float) -> float:
    return round(min(1.0, _ROUTE_BASE[route] + 0.1 * jaccard), 4)


def _marker(norm_sentence: str):
    """Parse a documented first-person marker pattern, or return None.

    Returns (marker_kind, polarity, verb, object) where polarity is +1/-1.
    """
    positive = _MARKER_POS.match(norm_sentence)
    if positive:
        return ('preference', 1, positive.group(1), positive.group(2).strip())
    negated = _MARKER_NEGATED.match(norm_sentence)
    if negated:
        return ('preference', -1, negated.group(1), negated.group(2).strip())
    negative = _MARKER_NEG_VERB.match(norm_sentence)
    if negative:
        return ('preference', -1, negative.group(1), negative.group(2).strip())
    always = _FREQ_POS.match(norm_sentence)
    if always:
        return ('frequency', 1, 'always', always.group(1).strip())
    never = _FREQ_NEG.match(norm_sentence)
    if never:
        return ('frequency', -1, 'never', never.group(1).strip())
    return None


class _Sentence:
    __slots__ = ('raw', 'norm', 'tokens', 'core', 'negated', 'marker',
                 'reversal', 'favorite')

    def __init__(self, raw: str):
        self.raw = raw
        self.norm = _normalize(raw)
        toks = _TOKEN.findall(self.norm)
        self.tokens = frozenset(toks)
        self.core = _content(t for t in toks if t not in _NEGATIONS)
        self.negated = any(t in _NEGATIONS for t in toks)
        self.marker = _marker(self.norm)
        reversal = _REVERSAL.match(self.norm)
        self.reversal = None
        if reversal:
            winner, loser = reversal.group(1).strip(), reversal.group(2).strip()
            if winner and loser and winner != loser:
                self.reversal = (winner, loser)
        favorite = _FAVORITE.match(self.norm)
        self.favorite = None
        if favorite:
            slot = ' '.join(favorite.group(1).split())
            value = favorite.group(2).strip()
            if slot and value and len(slot) <= 40 and len(value) <= 80:
                self.favorite = (slot, value)


class _Record:
    __slots__ = ('table', 'record_id', 'group', 'tags', 'sentences', 'tokens',
                 'scenario_sig', 'choice_norm', 'scenario_raw')

    def __init__(self, table: str, record_id: int, group: str, text: str):
        self.table = table
        self.record_id = record_id
        self.group = group            # identity kind; '' for other tables
        self.tags: list[str] = []     # episode tags; [] for other tables
        self.sentences = [_Sentence(s) for s in _sentences(text)] or [_Sentence(text)]
        self.tokens = _content(_tokens(text))
        self.scenario_sig = frozenset()
        self.choice_norm = ''
        self.scenario_raw = ''


def _load_records(db) -> tuple[dict[str, list[_Record]], dict[str, set[int]]]:
    """Read one consistent snapshot of approved records plus existence sets."""
    if db.in_transaction:
        raise ContradictionReviewError('Contradiction scan requires an idle database transaction')
    db.execute('BEGIN')
    try:
        existing: dict[str, set[int]] = {}
        for table in TABLES:
            existing[table] = {int(r[0]) for r in db.execute(f'SELECT id FROM {table}')}
        records: dict[str, list[_Record]] = {table: [] for table in TABLES}
        for row in db.execute(
                "SELECT id,kind,text FROM identity WHERE status='approved' ORDER BY id"):
            records['identity'].append(
                _Record('identity', int(row['id']), row['kind'], row['text']))
        for row in db.execute(
                "SELECT id,scenario,choice FROM decisions WHERE status='approved' ORDER BY id"):
            record = _Record('decisions', int(row['id']), '',
                             row['scenario'] + '. ' + row['choice'])
            record.scenario_sig = _content(_tokens(row['scenario']))
            record.choice_norm = _normalize(row['choice'])
            record.scenario_raw = row['scenario']
            records['decisions'].append(record)
        for row in db.execute(
                "SELECT id,topic,detail,tags_json FROM episodes WHERE status='approved' ORDER BY id"):
            record = _Record('episodes', int(row['id']), '',
                             row['topic'] + '. ' + row['detail'])
            record.tags = sorted(json.loads(row['tags_json']))
            records['episodes'].append(record)
        for table in TABLES:
            if len(records[table]) > MAX_SCAN_PER_TABLE:
                raise ContradictionReviewError(
                    f'Too many approved {table} records for a complete bounded scan')
        return records, existing
    finally:
        db.rollback()


def _pair_key(a: _Record, b: _Record) -> tuple[_Record, _Record]:
    return (a, b) if a.record_id < b.record_id else (b, a)


def _emit(found: dict, a: _Record, b: _Record, route: str, signal_key: str,
          signals: dict, jaccard: float) -> None:
    first, second = _pair_key(a, b)
    if first is not a:
        # Canonical order swapped the sides; swap the side-labelled signals.
        signals = dict(signals)
        for left, right in (('fragment_a', 'fragment_b'), ('value_a', 'value_b'),
                            ('verb_a', 'verb_b'), ('winner_a', 'winner_b'),
                            ('choice_a', 'choice_b')):
            if left in signals or right in signals:
                signals[left], signals[right] = signals.get(right), signals.get(left)
        if signals.get('negated_side') in ('a', 'b'):
            signals['negated_side'] = 'b' if signals['negated_side'] == 'a' else 'a'
    key = (first.table, first.record_id, second.record_id, route, signal_key)
    signals = {'route': route, 'jaccard': round(jaccard, 4),
               'shared_tokens': signals.pop('shared_tokens', []), **signals}
    candidate = {'a_table': first.table, 'a_id': first.record_id,
                 'b_table': second.table, 'b_id': second.record_id,
                 'route': route, 'signal_key': signal_key,
                 'signals': signals, 'score': _score(route, jaccard)}
    current = found.get(key)
    if current is None or candidate['score'] > current['score']:
        found[key] = candidate


def _shared(a: frozenset, b: frozenset) -> list[str]:
    return sorted(a & b)[:24]


def _detect(records: dict[str, list[_Record]]) -> list[dict]:
    """Pure detection over loaded records. Deterministic ordering throughout."""
    found: dict[tuple, dict] = {}
    for table in TABLES:
        rows = records[table]
        if len(rows) < 2:
            continue

        def compatible(a: _Record, b: _Record) -> bool:
            # Identity claims are only paired within the same kind; other
            # tables pair freely within themselves.
            return table != 'identity' or a.group == b.group

        # -- conflicting-slot: reversed preference pairs -------------------
        reversal_index: dict[tuple, list] = {}
        for record in rows:
            for sentence in record.sentences:
                if sentence.reversal:
                    winner, loser = sentence.reversal
                    key = tuple(sorted((winner, loser)))
                    reversal_index.setdefault(key, []).append(
                        (record, sentence, winner))
        for key in sorted(reversal_index):
            entries = reversal_index[key]
            made = 0
            for i in range(len(entries)):
                for j in range(i + 1, len(entries)):
                    if made >= MAX_PAIRS_PER_SIGNAL:
                        break
                    ra, sa, wa = entries[i]
                    rb, sb, wb = entries[j]
                    if ra.record_id == rb.record_id or wa == wb or not compatible(ra, rb):
                        continue
                    _emit(found, ra, rb, 'conflicting-slot', 'reversal:' + '|'.join(key),
                          {'slot': 'preference-reversal',
                           'shared_tokens': _shared(sa.tokens, sb.tokens),
                           'fragment_a': _fragment(sa.raw), 'fragment_b': _fragment(sb.raw),
                           'winner_a': wa, 'winner_b': wb},
                          _jaccard(sa.tokens, sb.tokens))
                    made += 1

        # -- conflicting-slot: favourite-<slot> values ----------------------
        favorite_index: dict[str, list] = {}
        for record in rows:
            for sentence in record.sentences:
                if sentence.favorite:
                    slot, value = sentence.favorite
                    favorite_index.setdefault(slot, []).append((record, sentence, value))
        for slot in sorted(favorite_index):
            entries = favorite_index[slot]
            made = 0
            for i in range(len(entries)):
                for j in range(i + 1, len(entries)):
                    if made >= MAX_PAIRS_PER_SIGNAL:
                        break
                    ra, sa, va = entries[i]
                    rb, sb, vb = entries[j]
                    if ra.record_id == rb.record_id or va == vb or not compatible(ra, rb):
                        continue
                    _emit(found, ra, rb, 'conflicting-slot', 'favorite:' + slot,
                          {'slot': 'favorite', 'slot_name': slot,
                           'shared_tokens': _shared(sa.tokens, sb.tokens),
                           'fragment_a': _fragment(sa.raw), 'fragment_b': _fragment(sb.raw),
                           'value_a': va, 'value_b': vb},
                          _jaccard(sa.tokens, sb.tokens))
                    made += 1

        # -- conflicting-slot: identical decision scenario, different choice
        if table == 'decisions':
            by_sig: dict[frozenset, list] = {}
            for record in rows:
                if record.scenario_sig:
                    by_sig.setdefault(record.scenario_sig, []).append(record)
            for sig in sorted(by_sig, key=lambda s: sorted(s)):
                entries = by_sig[sig]
                made = 0
                for i in range(len(entries)):
                    for j in range(i + 1, len(entries)):
                        if made >= MAX_PAIRS_PER_SIGNAL:
                            break
                        ra, rb = entries[i], entries[j]
                        if ra.choice_norm == rb.choice_norm:
                            continue
                        digest = hashlib.sha1(
                            ' '.join(sorted(sig)).encode('utf-8')).hexdigest()[:12]
                        _emit(found, ra, rb, 'conflicting-slot', 'scenario:' + digest,
                              {'slot': 'decision-scenario',
                               'shared_tokens': _shared(ra.tokens, rb.tokens),
                               'fragment_a': _fragment(ra.scenario_raw),
                               'fragment_b': _fragment(rb.scenario_raw),
                               'choice_a': ra.choice_norm, 'choice_b': rb.choice_norm},
                              _jaccard(ra.scenario_sig, rb.scenario_sig))
                        made += 1

        # -- opposite-preference markers ------------------------------------
        marker_index: dict[tuple, list] = {}
        for record in rows:
            for sentence in record.sentences:
                if sentence.marker:
                    kind, polarity, verb, obj = sentence.marker
                    if obj and len(obj) <= 120 and _content(_tokens(obj)):
                        marker_index.setdefault((kind, obj), []).append(
                            (record, sentence, polarity, verb))
        for key in sorted(marker_index):
            kind, obj = key
            entries = marker_index[key]
            positives = [e for e in entries if e[2] > 0]
            negatives = [e for e in entries if e[2] < 0]
            made = 0
            for ra, sa, _pa, va in positives:
                for rb, sb, _pb, vb in negatives:
                    if made >= MAX_PAIRS_PER_SIGNAL:
                        break
                    if ra.record_id == rb.record_id or not compatible(ra, rb):
                        continue
                    _emit(found, ra, rb, 'opposite-preference', f'{kind}:{obj}',
                          {'slot': kind, 'object': obj,
                           'shared_tokens': _shared(sa.tokens, sb.tokens),
                           'fragment_a': _fragment(sa.raw), 'fragment_b': _fragment(sb.raw),
                           'verb_a': va, 'verb_b': vb},
                          _jaccard(sa.tokens, sb.tokens))
                    made += 1

        # -- negation asymmetry ----------------------------------------------
        buckets: dict[str, set[int]] = {}
        for record in rows:
            record_tokens = set()
            for sentence in record.sentences:
                record_tokens |= sentence.core
            for token in record_tokens:
                buckets.setdefault(token, set()).add(record.record_id)
        pair_ids: set[tuple[int, int]] = set()
        for token, ids in buckets.items():
            if len(ids) > MAX_BUCKET_RECORDS:
                continue
            ordered = sorted(ids)
            for i in range(len(ordered)):
                for j in range(i + 1, len(ordered)):
                    pair_ids.add((ordered[i], ordered[j]))
        by_id = {record.record_id: record for record in rows}
        for low, high in sorted(pair_ids):
            ra, rb = by_id[low], by_id[high]
            if not compatible(ra, rb):
                continue
            for sa in ra.sentences:
                for sb in rb.sentences:
                    if sa.negated == sb.negated:
                        continue
                    if not sa.core or not sb.core:
                        continue
                    overlap = _jaccard(sa.core, sb.core)
                    if overlap < NEGATION_JACCARD_MIN:
                        continue
                    digest = hashlib.sha1(' '.join(sorted(sa.core & sb.core)).encode(
                        'utf-8')).hexdigest()[:12]
                    _emit(found, ra, rb, 'negation-asymmetry', 'negation:' + digest,
                          {'shared_tokens': _shared(sa.core, sb.core),
                           'fragment_a': _fragment(sa.raw), 'fragment_b': _fragment(sb.raw),
                           'negated_side': 'a' if sa.negated else 'b'},
                          overlap)
    # Episode pairs also record their shared tags: tags are the topical
    # link the owner used when filing the episodes, alongside the lexical
    # gate each route already enforced.
    by_episode = {r.record_id: r for r in records['episodes']}
    for candidate in found.values():
        if candidate['a_table'] == 'episodes':
            shared_tags = sorted(set(by_episode[candidate['a_id']].tags)
                                 & set(by_episode[candidate['b_id']].tags))
            if shared_tags:
                candidate['signals']['shared_tags'] = shared_tags
    return [found[key] for key in sorted(found)]


# ---------------------------------------------------------------------------
# Store (A2 style: private profile tables, one handle per operation)
# ---------------------------------------------------------------------------

class ContradictionStore:
    """Candidate + adjudication store in the private profile database."""

    def __init__(self, home: Path | None = None):
        self.home = Path(home) if home is not None else None
        with self._open() as store:
            store.db.execute('''CREATE TABLE IF NOT EXISTS contradiction_candidates (
                id INTEGER PRIMARY KEY,
                a_table TEXT NOT NULL CHECK(a_table IN ('identity','decisions','episodes')),
                a_id INTEGER NOT NULL,
                b_table TEXT NOT NULL CHECK(b_table IN ('identity','decisions','episodes')),
                b_id INTEGER NOT NULL,
                route TEXT NOT NULL CHECK(route IN
                    ('negation-asymmetry','opposite-preference','conflicting-slot')),
                signal_key TEXT NOT NULL,
                signals_json TEXT NOT NULL DEFAULT '{}',
                score REAL NOT NULL,
                state TEXT NOT NULL DEFAULT 'pending'
                    CHECK(state IN ('pending','confirmed','dismissed','deferred')),
                created_at TEXT NOT NULL,
                updated_at TEXT NOT NULL,
                UNIQUE(a_table,a_id,b_table,b_id,route,signal_key),
                CHECK(a_table = b_table AND a_id < b_id)
            )''')
            store.db.execute('''CREATE INDEX IF NOT EXISTS idx_contradiction_candidates_state
                ON contradiction_candidates(state, score DESC, id)''')
            store.db.execute('''CREATE TABLE IF NOT EXISTS contradiction_adjudications (
                id INTEGER PRIMARY KEY,
                candidate_id INTEGER NOT NULL,
                a_table TEXT NOT NULL, a_id INTEGER NOT NULL,
                b_table TEXT NOT NULL, b_id INTEGER NOT NULL,
                route TEXT NOT NULL,
                actor TEXT NOT NULL DEFAULT 'owner',
                action TEXT NOT NULL CHECK(action IN ('confirm','dismiss','defer')),
                resolution TEXT CHECK(resolution IN ('keep-a','keep-b','keep-both')),
                note TEXT NOT NULL DEFAULT '',
                superseded_table TEXT, superseded_id INTEGER,
                created_at TEXT NOT NULL
            )''')
            store.db.execute('''CREATE INDEX IF NOT EXISTS idx_contradiction_adjudications_candidate
                ON contradiction_adjudications(candidate_id, id)''')
            store.db.commit()

    @contextmanager
    def _open(self):
        store = ExperienceStore(self.home)
        try:
            yield store
        finally:
            store.close()

    # -- detection ---------------------------------------------------------

    def scan(self) -> dict:
        """Run detection and persist NEW candidates. Records are never touched.

        Candidates whose records have been deleted outright are pruned so
        erased content does not linger as derived fragments; adjudication
        history (metadata only) is kept.
        """
        with self._open() as store:
            records, _existing = _load_records(store.db)
            detected = _detect(records)
            created = already = pruned = 0
            truncated = False
            when = utc_now()
            with store.db:
                store.db.execute('BEGIN IMMEDIATE')
                for table in TABLES:
                    cursor = store.db.execute(
                        f'''DELETE FROM contradiction_candidates WHERE a_table=?
                            AND (a_id NOT IN (SELECT id FROM {table})
                                 OR b_id NOT IN (SELECT id FROM {table}))''', (table,))
                    pruned += cursor.rowcount
                for candidate in detected:
                    if created >= MAX_NEW_PER_SCAN:
                        truncated = True
                        break
                    cursor = store.db.execute(
                        '''INSERT OR IGNORE INTO contradiction_candidates
                           (a_table,a_id,b_table,b_id,route,signal_key,signals_json,
                            score,state,created_at,updated_at)
                           VALUES (?,?,?,?,?,?,?,?,'pending',?,?)''',
                        (candidate['a_table'], candidate['a_id'], candidate['b_table'],
                         candidate['b_id'], candidate['route'], candidate['signal_key'],
                         json.dumps(candidate['signals'], sort_keys=True, ensure_ascii=False),
                         candidate['score'], when, when))
                    if cursor.rowcount:
                        created += 1
                    else:
                        already += 1
            by_route = {route: 0 for route in ROUTES}
            for candidate in detected:
                by_route[candidate['route']] += 1
            return {'schema': 1, 'status': 'scan-complete',
                    'records_scanned': {table: len(records[table]) for table in TABLES},
                    'detected': len(detected), 'by_route': by_route,
                    'created': created, 'already_known': already,
                    'pruned_orphaned': pruned, 'truncated': truncated,
                    'records_modified': False, 'automatic_adjudication': False}

    # -- reads ---------------------------------------------------------------

    @staticmethod
    def _candidate_dict(store, row) -> dict:
        out = dict(row)
        out['signals'] = json.loads(out.pop('signals_json'))
        out['records_still_approved'] = all(
            store.db.execute(
                f"SELECT 1 FROM {out[side + '_table']} WHERE id=? AND status='approved'",
                (out[side + '_id'],)).fetchone() is not None
            for side in ('a', 'b'))
        return out

    def candidates(self, *, state: str = 'actionable', limit: int = 80) -> list[dict]:
        if state == 'actionable':
            clause, args = "state IN ('pending','deferred')", ()
        elif state == 'all':
            clause, args = '1=1', ()
        elif state in CANDIDATE_STATES:
            clause, args = 'state=?', (state,)
        else:
            raise ContradictionReviewError(f'Unknown candidate state filter: {state}')
        if type(limit) is not int or not 1 <= limit <= 500:
            raise ContradictionReviewError('Candidate list limit must be 1–500')
        with self._open() as store:
            rows = store.db.execute(
                f'SELECT * FROM contradiction_candidates WHERE {clause} '
                'ORDER BY score DESC, id ASC LIMIT ?', (*args, limit)).fetchall()
            return [self._candidate_dict(store, row) for row in rows]

    def get(self, candidate_id: int) -> dict | None:
        if type(candidate_id) is not int or candidate_id <= 0:
            raise ContradictionReviewError('Choose a valid candidate ID')
        with self._open() as store:
            row = store.db.execute(
                'SELECT * FROM contradiction_candidates WHERE id=?',
                (candidate_id,)).fetchone()
            return None if row is None else self._candidate_dict(store, row)

    def detail(self, candidate_id: int) -> dict:
        """Full candidate plus both complete records (PRIVATE content)."""
        with self._open() as store:
            row = store.db.execute(
                'SELECT * FROM contradiction_candidates WHERE id=?',
                (candidate_id,)).fetchone()
            if row is None:
                raise ContradictionReviewError('Unknown candidate ID')
            candidate = self._candidate_dict(store, row)
            records = {}
            for side in ('a', 'b'):
                table, record_id = candidate[side + '_table'], candidate[side + '_id']
                found = store.db.execute(
                    f'SELECT * FROM {table} WHERE id=?', (record_id,)).fetchone()
                records[side] = None if found is None else dict(found)
            history = [dict(r) for r in store.db.execute(
                'SELECT * FROM contradiction_adjudications WHERE candidate_id=? ORDER BY id',
                (candidate_id,))]
            return {'schema': 1, 'candidate': candidate, 'record_a': records['a'],
                    'record_b': records['b'], 'adjudications': history,
                    'private_data_in_output': True}

    def adjudications(self, candidate_id: int) -> list[dict]:
        with self._open() as store:
            return [dict(r) for r in store.db.execute(
                'SELECT * FROM contradiction_adjudications WHERE candidate_id=? ORDER BY id',
                (candidate_id,))]

    # -- adjudication ----------------------------------------------------------

    def adjudicate(self, candidate_id: int, *, action: str,
                   resolution: str | None = None, note: str = '',
                   actor: str = 'owner', confirmed: bool = False) -> dict:
        """Apply ONE explicit owner decision to ONE candidate.

        confirm + keep-a/keep-b supersedes the loser through the existing
        machinery (status transition + append-only 'superseded' event, as
        in conflict_review). keep-both, dismiss and defer change no record.
        """
        if confirmed is not True:
            raise ContradictionReviewError(
                'Explicit --confirm required to adjudicate a candidate')
        if type(candidate_id) is not int or candidate_id <= 0:
            raise ContradictionReviewError('Choose a valid candidate ID')
        if action not in ('confirm', 'dismiss', 'defer'):
            raise ContradictionReviewError('Choose confirm, dismiss or defer')
        if action == 'confirm':
            if resolution not in ('keep-a', 'keep-b', 'keep-both'):
                raise ContradictionReviewError(
                    'Confirm requires a resolution: keep-a, keep-b or keep-both')
        elif resolution is not None:
            raise ContradictionReviewError('Only confirm takes a resolution')
        if not isinstance(note, str) or len(note) > MAX_NOTE:
            raise ContradictionReviewError(f'Note must be at most {MAX_NOTE} characters')
        if not isinstance(actor, str) or not actor.strip() or len(actor) > 40:
            raise ContradictionReviewError('Actor must be a short non-empty label')
        with self._open() as store:
            with store.db:
                # Re-read everything under the write lock: a candidate whose
                # records changed since review fails closed, with no writes.
                store.db.execute('BEGIN IMMEDIATE')
                row = store.db.execute(
                    'SELECT * FROM contradiction_candidates WHERE id=?',
                    (candidate_id,)).fetchone()
                if row is None:
                    raise ContradictionReviewError('Unknown candidate ID')
                if row['state'] not in ('pending', 'deferred'):
                    raise ContradictionReviewError(
                        f"Candidate is already {row['state']} and cannot be adjudicated again")
                sides = {}
                for side in ('a', 'b'):
                    table, record_id = row[side + '_table'], row[side + '_id']
                    record = store.db.execute(
                        f'SELECT status FROM {table} WHERE id=?', (record_id,)).fetchone()
                    if record is None or record['status'] != 'approved':
                        raise ContradictionReviewError(
                            'A paired record is no longer approved; the candidate is stale')
                    sides[side] = (table, record_id)
                when = utc_now()
                superseded = None
                if action == 'confirm' and resolution in ('keep-a', 'keep-b'):
                    loser_side = 'b' if resolution == 'keep-a' else 'a'
                    table, loser_id = sides[loser_side]
                    if table == 'decisions':
                        cursor = store.db.execute(
                            "UPDATE decisions SET status='rejected' WHERE id=? AND status='approved'",
                            (loser_id,))
                    else:
                        cursor = store.db.execute(
                            f"UPDATE {table} SET status='rejected', updated_at=? "
                            "WHERE id=? AND status='approved'", (when, loser_id))
                    if cursor.rowcount != 1:
                        raise ContradictionReviewError('Losing record changed; adjudication refused')
                    store._event('superseded', table, loser_id)
                    superseded = {'table': table, 'id': loser_id}
                new_state = {'confirm': 'confirmed', 'dismiss': 'dismissed',
                             'defer': 'deferred'}[action]
                store.db.execute(
                    'UPDATE contradiction_candidates SET state=?, updated_at=? WHERE id=?',
                    (new_state, when, candidate_id))
                cursor = store.db.execute(
                    '''INSERT INTO contradiction_adjudications
                       (candidate_id,a_table,a_id,b_table,b_id,route,actor,action,
                        resolution,note,superseded_table,superseded_id,created_at)
                       VALUES (?,?,?,?,?,?,?,?,?,?,?,?,?)''',
                    (candidate_id, row['a_table'], row['a_id'], row['b_table'],
                     row['b_id'], row['route'], actor.strip(), action, resolution,
                     note.strip(), None if superseded is None else superseded['table'],
                     None if superseded is None else superseded['id'], when))
                store._event('contradiction-' + action, 'contradiction_candidates',
                             candidate_id)
            return {'schema': 1, 'candidate_id': candidate_id,
                    'adjudication_id': int(cursor.lastrowid), 'action': action,
                    'resolution': resolution, 'state': new_state,
                    'superseded': superseded,
                    'records_changed': superseded is not None,
                    'automatic_resolution': False}


# ---------------------------------------------------------------------------
# Profile-level helpers for the CLI (existing profile required, as in
# conflict_review: detection tooling never creates a profile by accident)
