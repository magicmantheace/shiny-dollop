"""Bounded composition of public numeric feature programs from generic operators.

Unlike fixed known-law lookup, candidate programs are generated by a generic
small grammar (multiply, add, modulo) over anonymous public sensor values.
The grammar itself was designed by a human and CONTAINS the authored hidden
target formulas; this is finite program synthesis and predictive selection,
not open-ended law invention, independent causal discovery or safe autonomy.
"""
from __future__ import annotations

import itertools
import json
import math

from developmental_ai.feature_hypothesis_memory import _Bucket
from developmental_ai.relation_outcome_memory import RelationOutcomeMemory
from developmental_ai.observable_affordances import (
    MAX_SAMPLES, VariableOutcomeMemory, canonical, digest,
)

SCHEMA="developmental-ai.composed-feature-memory/v1"
SOURCE=192
WARMUP=240
RECENT_TRAIN=24
ACTION_TRAIN=32
TAIL=12
ALPHA=0.25
QUADRATIC_PENALTY=0.25

# Generic arithmetic grammar, not a prewritten mapping from target world
# identifiers to correct feature formulas. Each tuple is
# (left_mul_leaf, right_mul_leaf, linear_leaf, quadratic_coef,
#  linear_coef, modulus). It represents
# ((quadratic_coef * (x*y)) + linear_coef*z) % modulus.
PROGRAMS=tuple(itertools.product(
    ((0,0),(0,1),(1,1)),(0,1),(1,2),(1,2),(5,7)
))
FIXED=("frozen_source_span","recent_span","recent_checksum","recent_ordered")
MODEL_NAMES=FIXED+tuple("composed_"+str(i) for i in range(len(PROGRAMS)))


def bucket_for(program,features):
    if type(features) is not dict or len(features)!=2:
        raise ValueError("composed features require two public numeric inputs")
    numbers=[features[key] for key in sorted(features)]
    (pair,linear,coefficient_product,coefficient_linear,modulus)=program
    result=(coefficient_product*(numbers[pair[0]]*numbers[pair[1]])+
            coefficient_linear*numbers[linear])%modulus
    return result


class _ComposedBucket:
    def __init__(self,program,events):
        if program not in PROGRAMS:
            raise ValueError("program outside frozen grammar")
        self.program=program
        self.counts=[[0,0,0] for _ in range(program[4])]
        for e in events:
            k=bucket_for(program,e["features"])
            self.counts[k][0 if e["progress"] else 1 if e["damage"] else 2]+=1

    def estimate(self,features):
        row=self.counts[bucket_for(self.program,features)]
        denom=sum(row)+3*ALPHA
        return tuple((n+ALPHA)/denom for n in row)

    def probability(self,event):
        outcome=0 if event["progress"] else 1 if event["damage"] else 2
        return self.estimate(event["features"])[outcome]

    def choose(self,frame):
        VariableOutcomeMemory().choose(frame)
        if frame["done"]:
            return None
        scores=[]
        for action in frame["actions"]:
            p,d,_=self.estimate(action["features"])
            scores.append((-(3*p-10*d),action["id"]))
        return min(scores)[1] if scores else None


class ComposedFeatureMemory:
    """Rank generated feature programs with prequential public feedback."""

    def __init__(self):
        self.events=[]
        self._cache=None

    def observe(self,event):
        if len(self.events)>=MAX_SAMPLES:
            raise ValueError("composed evidence cap exceeded")
        validator=RelationOutcomeMemory()
        validator.observe(event)
        sanitized=validator.events[0]
        if len(sanitized["features"])!=2 or (
                self.events and
                set(sanitized["features"])!=set(self.events[0]["features"])):
            raise ValueError("unexpected public feature schema")
        self.events.append(sanitized)
        self._cache=None

    @staticmethod
    def _learn_fixed(index,rows):
        if index==0 or index==1:
            return _Bucket("span",rows)
        if index==2:
            return _Bucket("checksum",rows)
        if index==3:
            return _Bucket("ordered",rows)
        return _ComposedBucket(PROGRAMS[index-len(FIXED)],rows)

    def selection(self):
        if self._cache is not None:
            return self._cache
        if len(self.events)<WARMUP:
            raise ValueError("insufficient source public events")
        source=self._learn_fixed(0,self.events[:SOURCE])
        log_scores=[0.0]*len(MODEL_NAMES)
        for i in range(len(self.events)-TAIL,len(self.events)):
            scored=self.events[i]
            previous=self.events[max(0,i-RECENT_TRAIN):i]
            for n in range(len(MODEL_NAMES)):
                prior=source if n==0 else self._learn_fixed(n,previous)
                prob=prior.probability(scored)
                if prob<=0 or not math.isfinite(prob):
                    raise ValueError("invalid predictive result")
                log_scores[n]+=math.log(prob)
        for j in range(len(FIXED),len(MODEL_NAMES)):
            log_scores[j]-=QUADRATIC_PENALTY
        # Enumeration order gives a deterministic tie-break in favor of
        # simpler fixed baselines. The grammar has no world-id lookup.
        best=max(range(len(MODEL_NAMES)),key=lambda j:log_scores[j])
        selected=(source if best==0 else
                  self._learn_fixed(best,self.events[-ACTION_TRAIN:]))
        report={
            "selected":MODEL_NAMES[best],
            "selected_program":(list(PROGRAMS[best-len(FIXED)])
                                if best>=len(FIXED) else None),
            "prequential_score":round(log_scores[best],6),
            "scoring_events":TAIL,
            "scoring_fit_overlap":0,
            "generated_program_count":len(PROGRAMS),
            "candidate_count":len(MODEL_NAMES),
            "source_retained":True,
            "recorded_events":len(self.events),
        }
        self._cache=report,selected
        return self._cache

    def choose(self,frame):
        VariableOutcomeMemory().choose(frame)
        if frame["done"]:
            return None
        if any(set(a["features"])!=set(self.events[0]["features"])
               for a in frame["actions"]):
            raise ValueError("candidate action sensors differ from public history")
        return self.selection()[1].choose(frame)

    def record(self):
        if not self.events:
            raise ValueError("empty composed feature memory")
        state={"schema":SCHEMA,"events":self.events}
        return {"state":json.loads(canonical(state)),"sha256":digest(state)}

    @classmethod
    def restore(cls,record):
        if (type(record) is not dict or set(record)!={"state","sha256"}
                or type(record["state"]) is not dict
                or type(record["sha256"]) is not str
                or digest(record["state"])!=record["sha256"]):
            raise ValueError("bad composed memory checkpoint hash")
        state=record["state"]
        if (set(state)!={"schema","events"} or state["schema"]!=SCHEMA
                or type(state["events"]) is not list or
                not 1<=len(state["events"])<=MAX_SAMPLES):
            raise ValueError("bad composed memory checkpoint structure")
        result=cls()
        for e in state["events"]:
            result.observe(e)
        if result.record()!=record:
            raise ValueError("bad composed memory deterministic replay")
        return result
