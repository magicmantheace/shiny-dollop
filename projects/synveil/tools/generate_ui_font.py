#!/usr/bin/env python3
"""Generate src/veil-display/ui_font_data.h for the veil-display UI.

The greeter/dashboard runs on a bare framebuffer with a static libc-only
binary, so it cannot link FreeType. This tool rasterizes the DejaVu Sans
faces that Buildroot already pins into the target rootfs into a compact
embedded bitmap atlas (PackBits RLE, ASCII 32..126, sizes 12/14/20/32/48,
regular + bold) that veil-display decodes at runtime.

UI_DESIGN.md names Selawik as the first-choice face. Selawik is not part of
any source tree this project pins, and fetching it would introduce an
unpinned artifact into the build, so the design's documented fallback --
DejaVu Sans with the spec's type metrics -- is what ships. The deviation is
recorded in the slice validation note (docs/validation/).

The generated header is the pinned artifact: it is committed, and this
generator is NOT invoked by rootfs.sh or the display self-test build, so no
build ever fetches or regenerates fonts. Regenerate deliberately with:

    python3 tools/generate_ui_font.py \
        out/native-weston/build/target/usr/share/fonts/dejavu/DejaVuSans.ttf \
        out/native-weston/build/target/usr/share/fonts/dejavu/DejaVuSans-Bold.ttf \
        src/veil-display/ui_font_data.h

The input files come from the Buildroot target tree, whose DejaVu version
is pinned by the Buildroot version the project vendors. The SHA-256 of both
inputs and the FreeType version used are recorded in the header comment so
any regeneration can be audited byte-for-byte.
"""

import hashlib
import sys

from PIL import ImageFont, features

FREETYPE_VERSION = features.version("freetype2") or "unknown"

SIZES = [12, 14, 20, 32, 48]
FIRST_CHAR = 32
LAST_CHAR = 126


def packbits(data: bytes) -> bytes:
    """Classic PackBits: literal runs (0..127) and repeats (129..255)."""
    out = bytearray()
    i = 0
    n = len(data)
    while i < n:
        run = 1
        while i + run < n and data[i + run] == data[i] and run < 128:
            run += 1
        if run >= 3:
            out.append(257 - run)
            out.append(data[i])
            i += run
            continue
        start = i
        literal = 0
        while i < n and literal < 128:
            r = 1
            while i + r < n and data[i + r] == data[i] and r < 128:
                r += 1
            if r >= 3 and literal > 0:
                break
            step = r if literal + r <= 128 else 128 - literal
            literal += step
            i += step
            if r >= 3:
                break
        out.append(literal - 1)
        out += data[start : start + literal]
    return bytes(out)


def rasterize(path: str, size: int):
    font = ImageFont.truetype(path, size)
    ascent, descent = font.getmetrics()
    glyphs = []
    blob = bytearray()
    for code in range(FIRST_CHAR, LAST_CHAR + 1):
        ch = chr(code)
        mask, (ox, oy) = font.getmask2(ch, mode="L")
        width, height = mask.size
        raw = bytes(mask) if width and height else b""
        assert len(raw) == width * height
        assert width <= 255 and height <= 255, (path, size, code, width, height)
        # FreeType convention: bitmap_top = distance from baseline to the
        # top of the bitmap. The PIL anchor is the ascender line, so
        # top = ascent - oy and left = ox.
        top = ascent - oy
        assert -32768 <= top <= 32767
        assert -128 <= ox <= 127, (path, size, code, ox)
        advance = round(font.getlength(ch))
        encoded = packbits(raw)
        glyphs.append(
            {
                "offset": len(blob),
                "advance": advance,
                "top": top,
                "width": width,
                "height": height,
                "left": ox,
            }
        )
        blob += encoded
    return ascent, descent, glyphs, bytes(blob)


def c_bytes(data: bytes, indent: str = "    ") -> str:
    lines = []
    for i in range(0, len(data), 16):
        chunk = data[i : i + 16]
        lines.append(indent + " ".join(f"0x{b:02x}," for b in chunk))
    return "\n".join(lines)


def main(argv):
    if len(argv) != 4:
        print(__doc__)
        return 2
    regular_path, bold_path, out_path = argv[1], argv[2], argv[3]
    faces = [("regular", 0, regular_path), ("bold", 1, bold_path)]
    digests = {}
    for _, _, path in faces:
        with open(path, "rb") as fh:
            digests[path] = hashlib.sha256(fh.read()).hexdigest()

    parts = []
    parts.append("/* GENERATED by tools/generate_ui_font.py -- do not edit. */")
    parts.append("/* Embedded DejaVu Sans bitmap atlas for veil-display.     */")
    parts.append(f"/* DejaVuSans.ttf      sha256 {digests[regular_path]} */")
    parts.append(f"/* DejaVuSans-Bold.ttf sha256 {digests[bold_path]} */")
    parts.append(
        f"/* FreeType {FREETYPE_VERSION} via Pillow ImageFont; "
        "PackBits RLE; ASCII 32..126. */"
    )
    parts.append("")
    parts.append("struct ui_glyph {")
    parts.append("    unsigned int data_offset;")
    parts.append("    unsigned short advance;")
    parts.append("    short top;")
    parts.append("    unsigned char width;")
    parts.append("    unsigned char height;")
    parts.append("    signed char left;")
    parts.append("};")
    parts.append("")
    parts.append("struct ui_font {")
    parts.append("    unsigned char size;")
    parts.append("    unsigned char bold;")
    parts.append("    unsigned short ascent;")
    parts.append("    unsigned short descent;")
    parts.append("    const struct ui_glyph *glyphs;")
    parts.append("    const unsigned char *data;")
    parts.append("};")
    parts.append("")

    index_entries = []
    for name, bold, path in faces:
        for size in SIZES:
            ascent, descent, glyphs, blob = rasterize(path, size)
            tag = f"{name}_{size}"
            parts.append(
                f"static const unsigned char ui_font_data_{tag}[] = {{"
            )
            parts.append(c_bytes(blob))
            parts.append("};")
            parts.append(
                f"static const struct ui_glyph ui_font_glyphs_{tag}[95] = {{"
            )
            for g in glyphs:
                parts.append(
                    "    {%d, %d, %d, %d, %d, %d},"
                    % (
                        g["offset"],
                        g["advance"],
                        g["top"],
                        g["width"],
                        g["height"],
                        g["left"],
                    )
                )
            parts.append("};")
            parts.append("")
            index_entries.append(
                "    {%d, %d, %d, %d, ui_font_glyphs_%s, ui_font_data_%s},"
                % (size, bold, ascent, descent, tag, tag)
            )
            print(
                f"{tag}: ascent={ascent} descent={descent} blob={len(blob)} bytes"
            )

    parts.append("static const struct ui_font ui_fonts[] = {")
    parts.extend(index_entries)
    parts.append("};")
    parts.append("")
    with open(out_path, "w", encoding="utf-8") as fh:
        fh.write("\n".join(parts))
    print(f"wrote {out_path}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv))
